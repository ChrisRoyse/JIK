"""Install-time version files declared for setuptools_scm (decision #12 roadblock E4).

setuptools_scm writes a version module during installation, so it never appears in a source tree.
Only a path the repository itself declares (pyproject `[tool.setuptools_scm] write_to/version_file`,
or a literal `use_scm_version={...}` in setup.py) is generated, with the declared template or the
setuptools_scm default, and an explicitly unknown version: the Git history needed to compute the
real one is not part of the pinned snapshot. Tests that assert a version will fail and stay gaps.
"""
from __future__ import annotations

import ast
import tomllib

VERSION = "0.0.0+mnlm.unknown"
DEFAULT_TEMPLATE = ("# file generated by setuptools_scm\n# don't change, don't track in version control\n"
                    "__version__ = version = {version!r}\n__version_tuple__ = version_tuple = {version_tuple!r}\n")
RULE = "setuptools_scm declared version file, unknown version (no Git history in the snapshot)"


def declared(files):
    """Returns (path, template) the repository declares, or None."""
    if "pyproject.toml" in files:
        try:
            scm = tomllib.loads(files["pyproject.toml"].decode("utf-8")).get("tool", {}).get("setuptools_scm", {})
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            scm = {}
        path = scm.get("version_file") or scm.get("write_to")
        if isinstance(path, str):
            return path, scm.get("version_file_template") or scm.get("write_to_template")
    if "setup.py" in files:
        try:
            tree = ast.parse(files["setup.py"].decode("utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            return None
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and getattr(node.func, "id", getattr(node.func, "attr", None)) == "setup":
                for kw in node.keywords:
                    if kw.arg == "use_scm_version" and isinstance(kw.value, ast.Dict):
                        try:
                            value = ast.literal_eval(kw.value)
                        except ValueError:
                            return None
                        path = value.get("write_to") or value.get("version_file")
                        if isinstance(path, str):
                            return path, value.get("write_to_template") or value.get("version_file_template")
    return None


def content(template):
    tuple_ = (0, 0, 0, "mnlm", "unknown")
    return (template or DEFAULT_TEMPLATE).format(version=VERSION, version_tuple=tuple_).encode("utf-8")


def generated(files):
    """[{path, content, rule}] for a declared version file that the snapshot lacks; else []."""
    found = declared(files)
    if not found or found[0].removeprefix("./") in files or not found[0].endswith(".py"):
        return []
    path, template = found
    return [{"path": path.removeprefix("./"), "content": content(template), "rule": RULE}]
